package com.doro.terminal.shell.linux

/**
 * Deterministic XDG user directory layout for the Ubuntu session.
 *
 * GNOME and Nautilus query these paths before the first application starts.
 * Keeping the paths ASCII avoids URL and shell quoting drift while the visible
 * labels remain localized through GTK bookmarks.
 */
internal object LinuxHubUserDirectories {
    const val locale = "zh_CN"

    val directories = listOf(
        "Desktop",
        "Documents",
        "Downloads",
        "Music",
        "Pictures",
        "Public",
        "Templates",
        "Videos",
    )

    private val labels = mapOf(
        "Desktop" to "桌面",
        "Documents" to "文档",
        "Downloads" to "下载",
        "Music" to "音乐",
        "Pictures" to "图片",
        "Public" to "公共",
        "Templates" to "模板",
        "Videos" to "视频",
    )

    fun userDirsFile(): String = buildString {
        append("# Generated by LinuxHub. XDG standard user directories.\n")
        append("XDG_DESKTOP_DIR=\"\$HOME/Desktop\"\n")
        append("XDG_DOWNLOAD_DIR=\"\$HOME/Downloads\"\n")
        append("XDG_TEMPLATES_DIR=\"\$HOME/Templates\"\n")
        append("XDG_PUBLICSHARE_DIR=\"\$HOME/Public\"\n")
        append("XDG_DOCUMENTS_DIR=\"\$HOME/Documents\"\n")
        append("XDG_MUSIC_DIR=\"\$HOME/Music\"\n")
        append("XDG_PICTURES_DIR=\"\$HOME/Pictures\"\n")
        append("XDG_VIDEOS_DIR=\"\$HOME/Videos\"\n")
    }

    fun bookmarksFile(username: String): String = directories.joinToString("\n", postfix = "\n") { name ->
        "file:///home/$username/$name ${labels.getValue(name)}"
    }

    fun recentlyUsedFile(): String =
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n" +
            "<xbel version=\"1.0\" " +
            "xmlns:bookmark=\"http://www.freedesktop.org/standards/desktop-bookmarks\" " +
            "xmlns:mime=\"http://www.freedesktop.org/standards/shared-mime-info\" />\n"
}
